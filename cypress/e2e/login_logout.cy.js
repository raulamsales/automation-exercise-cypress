beforeEach(() => {
    cy.visit('/')
})
it('Test Case 2: Login User with correct email and password', () => {
    cy.createTestUser()
    cy.visit('/')
    cy.get('a[href="/login"]').click()
    cy.get('[data-qa="login-email"]').type('uFNc~a36n2@mail.com')
    cy.get('[data-qa="login-password"]').type('uFNc~a36n2')
    cy.get('[data-qa="login-button"]').click()
    cy.contains('Logged in as').should('be.visible')
    cy.get('a[href="/delete_account"]', { timeout: 10000 }).click()
    cy.get('[data-qa="account-deleted"]').should('be.visible')
})

it('Test Case 3: Login User with incorrect email and password', () => {
    cy.get('#slider').should('be.visible')
    cy.get('a[href="/login"]').click()
    cy.contains('h2', 'Login to your account').should('be.visible')
    cy.get('[data-qa="login-email"]').type('invalid@mail.com')
    cy.get('[data-qa="login-password"]').type('wrongpassword')
    cy.get('[data-qa="login-button"]').click()
    cy.contains('Your email or password is incorrect!').should('be.visible')
})

